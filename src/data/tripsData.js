export const getTripBySlugOrId = (slugOrId) => {
  return tripsData.find(t => t.slug === slugOrId || String(t.id) === String(slugOrId));
};

export const getTripsByCategory = (categorySlug) => {
  return tripsData.filter(t => t.categorySlug === categorySlug);
};

export const getRelatedTrips = (currentSlugOrId, limit = 3) => {
  const current = getTripBySlugOrId(currentSlugOrId);
  if (!current) return tripsData.slice(0, limit);
  return tripsData
    .filter(t => t.id !== current.id && t.categorySlug === current.categorySlug)
    .slice(0, limit);
};
